export interface EmojiEntry {
  char: string
  name: string
  keywords: string
}

export interface EmojiCategory {
  id: string
  label: string
  /** Tab icon (a representative emoji from the category). */
  icon: string
  emojis: EmojiEntry[]
}

type Tuple = [string, string, string?]
const entries = (tuples: Tuple[]): EmojiEntry[] =>
  tuples.map(([char, name, keywords]) => ({ char, name, keywords: keywords ?? '' }))

